# -*- coding: utf-8 -*-
"""把 6300 行的 app.css 按「保序切片」拆成 3 个文件。

★为什么不「按功能抽取规则」：实测弹窗/表单规则在全文是**交错**的（弹窗在 401~4800 每段都有），
  抽取会让跨文件顺序变化 ⇒ 破坏原有级联（典型：末尾 6167 行的「弹窗尺寸档位」就是故意后置覆盖）。
  所以这里按**原文件物理顺序**切段，每段命名反映其主要内容，顺序与原来完全一致 ⇒ 零级联风险。

  切分点 2400 / 4980 均经括号深度校验（深度=0 的规则边界，不会切断 @media 块）。
"""
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'www', 'app.css')

lines = io.open(SRC, encoding='utf-8').read().split('\n')
N = len(lines)

# 校验切分点安全（深度为 0）
d = 0
depth = []
for ln in lines:
    d += ln.count('{') - ln.count('}')
    depth.append(d)
for cut in (2400, 4980):
    if depth[cut - 1] != 0:
        raise SystemExit('❌ 切分点 %d 深度=%d（不为 0），会切断规则块' % (cut, depth[cut - 1]))
if depth[-1] != 0:
    raise SystemExit('❌ 全文括号不平衡，末尾深度=%d' % depth[-1])

# index.html 里按这个顺序引入，不可调换
HEAD1 = """/* ============================================================================
 * app.css —— 基础层（变量 / 重置 / 字体 / 布局 / 导航 / 卡片 / 列表）
 * ★2026-10-25 从 6300 行单文件保序切分而来（第 1/3 段，原 1~2400 行）。
 *   切分原则：**只按原文件物理顺序切段，不重排任何规则** —— 弹窗/表单规则在全文是交错的，
 *   按功能抽取会改变跨文件顺序、破坏原有级联（末尾的「弹窗尺寸档位」就是故意后置覆盖）。
 *   ⇒ 引入顺序必须保持：app.css → app-modal.css → app-form.css，**不可调换**。
 * ============================================================================ */
"""
HEAD2 = """/* ============================================================================
 * app-modal.css —— 弹窗与浮层（confirm 弹窗 / 遮罩 / 数据管理说明 / toast 等）
 * ★第 2/3 段（原 2401~4980 行）。本段是全站弹窗规则最密集的区域。
 *   ⚠ 引入顺序在 app.css 之后、app-form.css 之前，不可调换（见 app.css 头部说明）。
 * ============================================================================ */
"""
HEAD3 = """/* ============================================================================
 * app-form.css —— 表单细节 / 末尾覆盖层（含「弹窗尺寸档位」等后置覆盖）
 * ★第 3/3 段（原 4981~6300 行）。**必须最后引入** —— 本段含刻意后置的覆盖规则。
 * ============================================================================ */
"""

parts = [
    ('app.css', HEAD1, lines[0:2400]),
    ('app-modal.css', HEAD2, lines[2400:4980]),
    ('app-form.css', HEAD3, lines[4980:]),
]

total = 0
for name, head, body in parts:
    p = os.path.join(ROOT, 'www', name)
    body = [ln for ln in body]
    # 去掉首段原有的开头空行冗余（保留内容）
    text = head + '\n'.join(body)
    if not text.endswith('\n'):
        text += '\n'
    io.open(p, 'w', encoding='utf-8', newline='').write(text)
    n = text.count('\n')
    total += n
    print('✅ %-16s %5d 行' % (name, n))

print('\n合计 %d 行（原 %d 行，差值为 3 个文件头注释）' % (total, N))
